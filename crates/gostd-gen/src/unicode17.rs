//! The Go std `unicode` tables (`GOSRC/unicode/tables.go`), ported from the generator
//! golang.org/x/text v0.27.0 `internal/export/unicode/gen.go`: the same category, script,
//! property, case-range, case-orbit and fold tables, from the same UCD files.

use crate::rangetable::{self, Table};
use crate::ucd;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

const MAX_CHAR: usize = 0x10FFFF;

/// The UCD files gen.go reads.
pub struct Files {
    pub unicode_data: String,
    pub case_folding: String,
    pub property_value_aliases: String,
    pub scripts: String,
    pub prop_list: String,
}

#[derive(Clone, Copy, Default)]
struct Char {
    code_point: u32, // 0: not a valid code point (gen.go: "if zero, this index is not valid")
    category: [u8; 2],
    upper: u32,
    lower: u32,
    title: u32,
    fold: u32,  // simple case folding (CaseFolding C and S)
    orbit: u32, // next in the simple case folding orbit
}

struct Data {
    chars: Vec<Char>,
    /// gen.go `category`: the merged names plus every category seen in UnicodeData.
    category: BTreeSet<String>,
    scripts: BTreeMap<String, Vec<u32>>,
    props: BTreeMap<String, Vec<u32>>,
}

fn cat(c: &Char) -> &str {
    std::str::from_utf8(&c.category).unwrap()
}

fn load(f: &Files) -> Data {
    let mut chars = vec![
        Char {
            category: *b"Cn",
            ..Char::default()
        };
        MAX_CHAR + 1
    ];
    let mut category: BTreeSet<String> = ["L", "LC", "P", "M", "N", "S", "Z", "C", "Cn"]
        .iter()
        .map(|s| s.to_string())
        .collect();
    // loadChars
    ucd::parse(&f.unicode_data, |p| {
        let get = |i: usize| {
            if p.string(i).is_empty() {
                0
            } else {
                p.rune_at(i)
            }
        };
        let gc = p.string(2);
        category.insert(gc.to_owned());
        let r = p.rune;
        let (upper, lower, title) = match gc {
            "Lu" => (r, get(13), get(14)),
            "Ll" => (get(12), r, get(14)),
            "Lt" => (get(12), get(13), r),
            _ => (get(12), get(13), get(14)),
        };
        let gc: [u8; 2] = gc.as_bytes().try_into().expect("two-letter category");
        chars[r as usize] = Char {
            code_point: r,
            category: gc,
            upper,
            lower,
            title,
            ..Char::default()
        };
    });
    // loadCasefold
    ucd::parse(&f.case_folding, |p| {
        if matches!(p.string(1), "C" | "S") {
            chars[p.rune as usize].fold = p.rune_at(2);
        }
    });
    let mut scripts: BTreeMap<String, Vec<u32>> = BTreeMap::new();
    ucd::parse(&f.scripts, |p| {
        scripts
            .entry(p.string(1).to_owned())
            .or_default()
            .push(p.rune)
    });
    let mut props: BTreeMap<String, Vec<u32>> = BTreeMap::new();
    ucd::parse(&f.prop_list, |p| {
        props
            .entry(p.string(1).to_owned())
            .or_default()
            .push(p.rune)
    });
    Data {
        chars,
        category,
        scripts,
        props,
    }
}

/// gen.go `deprecatedAliases`.
const DEPRECATED_ALIASES: &[(&str, &str)] = &[("Sentence_Terminal", "STerm")];

/// The Rust static name of a Go table: `Lu` -> `LU`, `White_Space` -> `WHITE_SPACE`.
fn ident(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

pub fn generate(f: &Files) -> String {
    let mut d = load(f);
    let mut out = String::new();
    let mut statics = BTreeSet::new();
    out.push_str("// Code generated by gostd-gen from UCD 17.0.0. DO NOT EDIT.\n");
    out.push_str("// The tables of Go std unicode (tables.go), from the generator of\n");
    out.push_str("// golang.org/x/text v0.27.0 internal/export/unicode/gen.go.\n\n");
    out.push_str("use super::{cr, r16, r32, CaseRange, RangeTable, UPPER_LOWER};\n\n");
    out.push_str("pub const VERSION: &str = \"17.0.0\";\n\n");

    // printCategories
    let cats: Vec<String> = d.category.iter().cloned().collect();
    map_decl(&mut out, "CATEGORIES", &cats, ident);
    category_aliases(&mut out, f, &d.category);
    for name in &cats {
        let runes: Vec<u32> = (0..=MAX_CHAR as u32)
            .filter(|&c| {
                let gc = cat(&d.chars[c as usize]);
                match name.as_str() {
                    "LC" => matches!(gc, "Ll" | "Lt" | "Lu"),
                    n if n.len() == 1 => gc.starts_with(n),
                    n => gc == n,
                }
            })
            .collect();
        table(
            &mut out,
            &mut statics,
            &ident(name),
            &rangetable::new(&runes),
        );
    }

    // printScriptOrProperty, scripts then properties
    for (list, map_name) in [(&d.scripts, "SCRIPTS"), (&d.props, "PROPERTIES")] {
        let mut keys: Vec<(String, String)> = Vec::new();
        for k in list.keys() {
            keys.push((k.clone(), k.clone()));
            if let Some((_, alias)) = DEPRECATED_ALIASES.iter().find(|(n, _)| n == k) {
                keys.push((alias.to_string(), k.clone()));
            }
        }
        keys.sort();
        writeln!(out, "pub static {map_name}: &[(&str, &RangeTable)] = &[").unwrap();
        for (k, target) in &keys {
            writeln!(out, "    ({k:?}, &{}),", ident(target)).unwrap();
        }
        out.push_str("];\n\n");
        for (name, runes) in list {
            table(
                &mut out,
                &mut statics,
                &ident(name),
                &rangetable::new(runes),
            );
        }
    }

    case_ranges(&mut out, &d.chars);
    case_orbit(&mut d.chars);
    out.push_str("pub static CASE_ORBIT: &[(u32, u32)] = &[\n");
    for (i, c) in d.chars.iter().enumerate() {
        if c.orbit != 0 {
            writeln!(out, "    (0x{i:04X}, 0x{:04X}),", c.orbit).unwrap();
        }
    }
    out.push_str("];\n\n");

    // FoldCategory and FoldScript
    let mut fold_cat: BTreeMap<String, BTreeSet<u32>> = BTreeMap::new();
    for name in &d.category {
        let class = in_category(&d.chars, name);
        let x = fold_exceptions(&d.chars, &class);
        if !x.is_empty() {
            fold_cat.insert(name.clone(), x);
        }
    }
    let mut fold_scr: BTreeMap<String, BTreeSet<u32>> = BTreeMap::new();
    for (name, runes) in &d.scripts {
        let x = fold_exceptions(&d.chars, runes);
        if !x.is_empty() {
            fold_scr.insert(name.clone(), x);
        }
    }
    for (map_name, m) in [("FOLD_CATEGORY", &fold_cat), ("FOLD_SCRIPT", &fold_scr)] {
        let keys: Vec<String> = m.keys().cloned().collect();
        map_decl(&mut out, map_name, &keys, |k| format!("FOLD_{}", ident(k)));
        for (name, class) in m {
            let runes: Vec<u32> = class.iter().copied().collect();
            table(
                &mut out,
                &mut statics,
                &format!("FOLD_{}", ident(name)),
                &rangetable::new(&runes),
            );
        }
    }
    out
}

fn map_decl(out: &mut String, name: &str, keys: &[String], to_static: impl Fn(&str) -> String) {
    writeln!(out, "pub static {name}: &[(&str, &RangeTable)] = &[").unwrap();
    for k in keys {
        writeln!(out, "    ({k:?}, &{}),", to_static(k)).unwrap();
    }
    out.push_str("];\n\n");
}

/// gen.go `printCategoryAliases`: PropertyValueAliases.txt `gc` lines, short and long names.
fn category_aliases(out: &mut String, f: &Files, known: &BTreeSet<String>) {
    let mut table = BTreeMap::new();
    ucd::parse(&f.property_value_aliases, |p| {
        if p.string(0) != "gc" {
            return;
        }
        let name = p.string(1).to_owned();
        assert!(known.contains(&name), "unknown category: {name}");
        table.insert(p.string(2).to_owned(), name.clone());
        if !p.string(3).is_empty() {
            table.insert(p.string(3).to_owned(), name);
        }
    });
    out.push_str("pub static CATEGORY_ALIASES: &[(&str, &str)] = &[\n");
    for (k, v) in &table {
        writeln!(out, "    ({k:?}, {v:?}),").unwrap();
    }
    out.push_str("];\n\n");
}

fn table(out: &mut String, statics: &mut BTreeSet<String>, name: &str, t: &Table) {
    assert!(statics.insert(name.to_owned()), "duplicate static {name}");
    writeln!(out, "pub static {name}: RangeTable = RangeTable {{").unwrap();
    out.push_str("    r16: &[\n");
    for r in &t.r16 {
        writeln!(
            out,
            "        r16(0x{:04x}, 0x{:04x}, {}),",
            r.lo, r.hi, r.stride
        )
        .unwrap();
    }
    out.push_str("    ],\n    r32: &[\n");
    for r in &t.r32 {
        writeln!(
            out,
            "        r32(0x{:x}, 0x{:x}, {}),",
            r.lo, r.hi, r.stride
        )
        .unwrap();
    }
    writeln!(out, "    ],\n    latin_offset: {},\n}};\n", t.latin_offset).unwrap();
}

// gen.go case states.
const CASE_NONE: i32 = 0;
const CASE_UPPER: i32 = 1;
const CASE_LOWER: i32 = 2;
const CASE_TITLE: i32 = 4;
const CASE_MISSING: i32 = -1;

#[derive(Clone, Copy, Default)]
struct CaseState {
    point: i64,
    case: i32,
    to_upper: i64,
    to_lower: i64,
    to_title: i64,
}

impl CaseState {
    fn adjacent(&self, other: &CaseState) -> bool {
        let (c, d) = if other.point < self.point {
            (other, self)
        } else {
            (self, other)
        };
        if d.point != c.point + 1 {
            false
        } else if d.case != c.case {
            c.upper_lower_adjacent(d)
        } else if c.case == CASE_NONE || c.case == CASE_MISSING {
            false
        } else {
            d.to_upper == c.to_upper && d.to_lower == c.to_lower && d.to_title == c.to_title
        }
    }

    fn upper_lower_adjacent(&self, other: &CaseState) -> bool {
        let (mut c, mut d) = (self, other);
        if (c.case == CASE_UPPER && d.case != CASE_LOWER)
            || (c.case == CASE_LOWER && d.case != CASE_UPPER)
        {
            return false;
        }
        if c.case == CASE_LOWER {
            (c, d) = (d, c);
        }
        c.is_upper_lower() && d.is_lower_upper()
    }

    fn is_upper_lower(&self) -> bool {
        self.to_upper == 0 && self.to_lower == 1 && self.to_title == 0
    }

    fn is_lower_upper(&self) -> bool {
        self.to_upper == -1 && self.to_lower == 0 && self.to_title == -1
    }
}

fn case_state(chars: &[Char], i: u32) -> CaseState {
    let ch = &chars[i as usize];
    let mut c = CaseState {
        point: i64::from(i),
        case: CASE_NONE,
        ..CaseState::default()
    };
    // gen.go: switch ch.codePoint { case 0: missing; case upper; case lower; case title }
    if ch.code_point == 0 {
        c.case = CASE_MISSING;
        return c;
    } else if ch.code_point == ch.upper {
        c.case = CASE_UPPER;
    } else if ch.code_point == ch.lower {
        c.case = CASE_LOWER;
    } else if ch.code_point == ch.title {
        c.case = CASE_TITLE;
    }
    if c.case == CASE_NONE && ch.lower != 0 {
        c.case = CASE_UPPER;
    }
    if c.case == CASE_NONE && ch.upper != 0 {
        c.case = CASE_LOWER;
    }
    let delta = |m: u32| {
        if m != 0 {
            i64::from(m) - i64::from(i)
        } else {
            0
        }
    };
    c.to_upper = delta(ch.upper);
    c.to_lower = delta(ch.lower);
    c.to_title = delta(ch.title);
    c
}

/// gen.go `printCases`.
fn case_ranges(out: &mut String, chars: &[Char]) {
    out.push_str("pub static CASE_RANGES: &[CaseRange] = &[\n");
    let mut start: Option<CaseState> = None;
    let mut prev = CaseState::default();
    for i in 0..=MAX_CHAR as u32 {
        let state = case_state(chars, i);
        if state.adjacent(&prev) {
            prev = state;
            continue;
        }
        if let Some(lo) = start {
            case_range(out, &lo, &prev);
        }
        start = (state.case != CASE_MISSING && state.case != CASE_NONE).then_some(state);
        prev = state;
    }
    out.push_str("];\n\n");
}

fn case_range(out: &mut String, lo: &CaseState, hi: &CaseState) {
    if lo.to_upper == 0 && lo.to_lower == 0 && lo.to_title == 0 {
        return;
    }
    if hi.point > lo.point && lo.is_upper_lower() {
        writeln!(
            out,
            "    cr(0x{:04X}, 0x{:04X}, [UPPER_LOWER, UPPER_LOWER, UPPER_LOWER]),",
            lo.point, hi.point
        )
        .unwrap();
    } else if hi.point > lo.point && lo.is_lower_upper() {
        panic!("LowerUpper sequence: should not happen: U+{:04X}", lo.point);
    } else {
        writeln!(
            out,
            "    cr(0x{:04X}, 0x{:04X}, [{}, {}, {}]),",
            lo.point, hi.point, lo.to_upper, lo.to_lower, lo.to_title
        )
        .unwrap();
    }
}

/// gen.go `printCasefold`, the orbit part: sets `Char::orbit`.
fn case_orbit(chars: &mut [Char]) {
    let mut orbit: Vec<Option<Vec<u32>>> = vec![None; MAX_CHAR + 1];
    for (i, c) in chars.iter().enumerate() {
        let f = c.fold;
        if f == 0 {
            continue;
        }
        orbit[f as usize]
            .get_or_insert_with(|| vec![f])
            .push(i as u32);
    }
    // Insert explicit 1-element groups when assuming [lower, upper] would be wrong.
    for (i, c) in chars.iter().enumerate() {
        let f = if c.fold == 0 { i } else { c.fold as usize };
        let me = i as u32;
        if orbit[f].is_none()
            && ((c.upper != 0 && c.upper != me) || (c.lower != 0 && c.lower != me))
        {
            orbit[i] = Some(vec![me]);
        }
    }
    // Delete the groups for which assuming [lower, upper] or [upper, lower] is right.
    for orb in orbit.iter_mut() {
        if let Some(o) = orb
            && o.len() == 2
        {
            let (a, b) = (o[0] as usize, o[1] as usize);
            if (chars[a].upper == o[1] && chars[b].lower == o[0])
                || (chars[b].upper == o[0] && chars[a].lower == o[1])
            {
                *orb = None;
            }
        }
    }
    for orb in orbit.into_iter().flatten() {
        let mut orb = orb;
        orb.sort_unstable();
        let mut c = *orb.last().unwrap();
        for &d in &orb {
            chars[c as usize].orbit = d;
            c = d;
        }
    }
}

/// gen.go `inCategory`: note that `LC` matches nothing here, as in Go.
fn in_category(chars: &[Char], name: &str) -> Vec<u32> {
    (0..=MAX_CHAR as u32)
        .filter(|&i| {
            let gc = cat(&chars[i as usize]);
            gc == name
                || (name.len() == 1 && gc.len() > 1 && gc.as_bytes()[0] == name.as_bytes()[0])
        })
        .collect()
}

/// gen.go `foldExceptions`.
fn fold_exceptions(chars: &[Char], class: &[u32]) -> BTreeSet<u32> {
    let mut m = BTreeSet::new();
    for &r in class {
        let c = &chars[r as usize];
        if c.orbit == 0 {
            if c.upper != 0 {
                m.insert(c.upper);
            }
            if c.lower != 0 {
                m.insert(c.lower);
            }
            m.insert(r);
            continue;
        }
        let mut x = r;
        loop {
            m.insert(x);
            x = chars[x as usize].orbit;
            if x == r {
                break;
            }
        }
    }
    for r in class {
        m.remove(r);
    }
    m
}

#[cfg(test)]
mod tests {
    use super::*;

    fn files(unicode_data: &str, case_folding: &str) -> Files {
        Files {
            unicode_data: unicode_data.into(),
            case_folding: case_folding.into(),
            property_value_aliases:
                "gc ; Lu ; Uppercase_Letter\ngc ; Ll ; Lowercase_Letter\ngc ; L ; Letter\n".into(),
            scripts: "0041..005A ; Latin\n".into(),
            prop_list: "0020 ; White_Space\n".into(),
        }
    }

    const AZ: &str = "0041;LATIN CAPITAL LETTER A;Lu;0;L;;;;;N;;;;0061;\n\
                      0042;LATIN CAPITAL LETTER B;Lu;0;L;;;;;N;;;;0062;\n\
                      0061;LATIN SMALL LETTER A;Ll;0;L;;;;;N;;;0041;;0041\n\
                      0062;LATIN SMALL LETTER B;Ll;0;L;;;;;N;;;0042;;0042\n\
                      004B;LATIN CAPITAL LETTER K;Lu;0;L;;;;;N;;;;006B;\n\
                      006B;LATIN SMALL LETTER K;Ll;0;L;;;;;N;;;004B;;004B\n\
                      212A;KELVIN SIGN;Lu;0;L;004B;;;;N;DEGREES KELVIN;;;006B;\n";
    const FOLD: &str = "0041; C; 0061;\n0042; C; 0062;\n004B; C; 006B;\n212A; C; 006B;\n";

    #[test]
    fn case_ranges_and_orbit() {
        let out = generate(&files(AZ, FOLD));
        assert!(
            out.contains("    cr(0x0041, 0x0042, [0, 32, 0]),\n"),
            "{out}"
        );
        assert!(
            out.contains("    cr(0x0061, 0x0062, [-32, 0, -32]),\n"),
            "{out}"
        );
        assert!(
            out.contains("    cr(0x212A, 0x212A, [0, -8383, 0]),\n"),
            "{out}"
        );
        // The K orbit: K -> k -> KELVIN SIGN -> K.
        assert!(
            out.contains("    (0x004B, 0x006B),\n    (0x006B, 0x212A),\n"),
            "{out}"
        );
        assert!(out.contains("    (0x212A, 0x004B),\n"), "{out}");
    }

    #[test]
    fn categories_aliases_and_fold() {
        let out = generate(&files(AZ, FOLD));
        assert!(out.contains("    (\"Lu\", &LU),\n"));
        assert!(out.contains("    (\"Uppercase_Letter\", \"Lu\"),\n"));
        assert!(out.contains("pub static LU: RangeTable = RangeTable {\n    r16: &[\n        r16(0x0041, 0x0042, 1),\n        r16(0x004b, 0x212a, 8415),\n    ],\n"), "{out}");
        // Lu folds to a, b, k outside Lu: FoldCategory["Lu"] holds 0x61, 0x62, 0x6b.
        assert!(out.contains("pub static FOLD_LU: RangeTable = RangeTable {\n    r16: &[\n        r16(0x0061, 0x0062, 1),\n        r16(0x006b, 0x006b, 1),\n    ],\n"), "{out}");
        assert!(out.contains("    (\"Latin\", &LATIN),\n"));
        assert!(out.contains("    (\"White_Space\", &WHITE_SPACE),\n"));
    }
}
