/// `(pat, path, is_dir, want)`.
type Case = (&'static str, &'static str, bool, bool);

/// Go's `{pat, path, isDir, want},` rows, verbatim.
macro_rules! cases {
    ($({$pat:literal, $path:literal, $dir:literal, $want:literal}),* $(,)?) => {
        &[$(($pat, $path, $dir, $want)),*]
    };
}

/// Go `TestIgnoreMatchesUpstream`: one pattern per case, through the pruning walk's ancestor
/// checks (`goIgnored`), against upstream 0.9.92 `_is_ignored` on real files.
#[test]
fn test_ignore_matches_upstream() {
    for &(pat, path, is_dir, want) in UPSTREAM_IGNORE_CASES {
        let rules = parse_ignore("", pat).rules;
        let got = go_ignored(&rules, path, is_dir);
        assert_eq!(
            got, want,
            "pattern {pat:?} path {path:?} dir={is_dir}: got {got}, upstream {want}"
        );
    }
}

/// Go `TestIgnoreClassNeverPanics`: odd character classes parse without a panic.
#[test]
fn test_ignore_class_never_panics() {
    for p in [
        "[[:alpha:]]",
        r"[\]",
        r"[a-\]",
        "[^-]",
        "[]-]",
        "[z-a-c]",
        r"[\d]",
        "[é-ü]",
        "[a-",
        "[[]]",
    ] {
        parse_ignore("", p);
        parse_ignore("", &format!("d/{p}"));
    }
}

/// Go `TestAnchoredDoesNotMatchDescendants`: `docs/*` with `!docs/keep/` keeps `docs/keep` and
/// prunes the other children.
#[test]
fn test_anchored_does_not_match_descendants() {
    let root = TempDir::new();
    must_write(&root.join(".gitignore"), "docs/*\n!docs/keep/\n");
    must_write(&root.join("docs/keep/x.md"), "x");
    must_write(&root.join("docs/other/y.md"), "y");
    let got = collected(root.path());
    assert!(
        got.contains("docs/keep/x.md") && !got.contains("docs/other/y.md"),
        "got {got:?}"
    );
}

/// Go `TestAncestorIgnoreFiles`: the ignore files and `info/exclude` above the scan root, up to
/// the VCS root, apply, with deeper files taking precedence.
#[test]
fn test_ancestor_ignore_files() {
    let (_d, repo) = resolved();
    let env = env_home(repo.join("nohome"));
    mk_git(&repo);
    must_write(
        &repo.join(".gitignore"),
        "*.gen.py\n/sub/x.go\n/sub/deep/*.tmp.py\nkeep.gen.py\n",
    );
    must_write(&repo.join(".git/info/exclude"), "excluded.py\n");
    must_write(
        &repo.join("sub/.graphifyignore"),
        "!keep.gen.py\nnotes.py\n",
    );
    must_write(&repo.join("sub/deep/.gitignore"), "!keep.gen.py\n");
    for f in [
        "x.go",
        "a.gen.py",
        "keep.gen.py",
        "excluded.py",
        "notes.py",
        "ok.go",
        "deep/z.tmp.py",
        "deep/keep.gen.py",
        "deep/b.gen.py",
        "other/x.go",
    ] {
        must_write(&repo.join("sub").join(f), "x");
    }
    let got = collected_env(&repo.join("sub"), &env);
    for f in ["ok.go", "keep.gen.py", "deep/keep.gen.py", "other/x.go"] {
        assert!(got.contains(f), "{f} should be collected, got {got:?}");
    }
    for f in [
        "x.go",
        "a.gen.py",
        "excluded.py",
        "notes.py",
        "deep/z.tmp.py",
        "deep/b.gen.py",
    ] {
        assert!(!got.contains(f), "{f} should be ignored, got {got:?}");
    }
}

/// Go `TestAncestorCeilingRules`: an invalid empty `.git` is not a ceiling, a `.git` above
/// `$HOME` does not count, and a `.git` file with `gitdir:` is a ceiling whose `info/exclude` is
/// found through `commondir`.
#[test]
fn test_ancestor_ceiling_rules() {
    // invalid empty .git is not a ceiling
    let (_d1, outer) = resolved();
    let env = env_home(outer.clone());
    must_write(&outer.join("mid/.gitignore"), "*.gen.py\n");
    std::fs::create_dir_all(outer.join("mid/.git")).expect("mkdir");
    must_write(&outer.join("mid/sub/a.gen.py"), "x");
    must_write(&outer.join("mid/sub/b.go"), "x");
    let got = collected_env(&outer.join("mid/sub"), &env);
    assert!(
        got.contains("a.gen.py") && got.contains("b.go"),
        "empty .git must not be a ceiling: {got:?}"
    );

    // .git above HOME does not count
    let (_d2, top) = resolved();
    mk_git(&top);
    must_write(&top.join(".gitignore"), "*.gen.py\n");
    let home = top.join("home");
    let env = env_home(home.clone());
    must_write(&home.join("proj/a.gen.py"), "x");
    let got = collected_env(&home.join("proj"), &env);
    assert!(
        got.contains("a.gen.py"),
        ".git above HOME must not count: {got:?}"
    );

    // .git file with gitdir: is a ceiling, info/exclude via commondir
    let (_d3, wt) = resolved();
    let env = env_home(wt.join("nohome"));
    let common = wt.join("common");
    let gd = common.join("worktrees/w");
    must_write(&gd.join("commondir"), "../..\n");
    must_write(&common.join("info/exclude"), "*.hid.py\n");
    let repo = wt.join("repo");
    must_write(&repo.join(".git"), &format!("gitdir: {}\n", gd.display()));
    must_write(&repo.join("sub/a.hid.py"), "x");
    must_write(&repo.join("sub/b.go"), "x");
    let got = collected_env(&repo.join("sub"), &env);
    assert!(
        !got.contains("a.hid.py") && got.contains("b.go"),
        "info/exclude of ceiling not applied: {got:?}"
    );
}

/// Go `TestIgnoreFileNotRegularNeverOpened`: a directory is not read as an ignore file.
